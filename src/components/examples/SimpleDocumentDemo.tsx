import React, { useState } from 'react';
import {
    Box,
    Typography,
    Button,
    Card,
    CardContent,
    Chip,
    LinearProgress,
    Alert,
    Fade,
    Paper,
} from '@mui/material';
import {
    AutoAwesome as AIIcon,
    Description as DocumentIcon,
    Download as DownloadIcon,
    PlayArrow as PlayIcon,
} from '@mui/icons-material';
import { styled, alpha } from '@mui/material/styles';
import { colors } from '../../styles/theme';

const DemoContainer = styled(Box)(() => ({
    padding: theme.spacing(3),
    borderRadius: 12,
    background: `linear-gradient(135deg, ${alpha(colors.primary.main, 0.02)}, ${alpha(colors.secondary.main, 0.02)})`,
    border: `1px solid ${alpha(colors.primary.main, 0.1)}`,
}));

const TemplateCard = styled(Card)(() => ({
    borderRadius: 12,
    border: `1px solid ${alpha(colors.primary.main, 0.1)}`,
    transition: 'all 0.2s ease-in-out',
    cursor: 'pointer',

    '&:hover': {
        transform: 'translateY(-2px)',
        boxShadow: `0 8px 24px ${alpha(colors.primary.main, 0.15)}`,
        borderColor: colors.primary.main,
    },

    '&.selected': {
        borderColor: colors.primary.main,
        backgroundColor: alpha(colors.primary.main, 0.05),
    },
}));

const GeneratedContent = styled(Paper)(() => ({
    padding: theme.spacing(3),
    borderRadius: 12,
    backgroundColor: colors.background.default,
    border: `1px solid ${alpha(colors.primary.main, 0.1)}`,
    fontFamily: 'monospace',
    fontSize: '0.875rem',
    lineHeight: 1.6,
    maxHeight: 400,
    overflow: 'auto',
}));

const templates = [
    {
        id: 'research-summary',
        title: 'Research Summary',
        description: 'Comprehensive overview of clinical trial findings',
        features: ['Executive summary', 'Key findings', 'Statistical analysis', 'Clinical implications'],
    },
    {
        id: 'literature-review',
        title: 'Literature Review',
        description: 'Systematic review of related clinical studies',
        features: ['Background research', 'Methodology comparison', 'Evidence synthesis', 'AMA citations'],
    },
    {
        id: 'patient-report',
        title: 'Patient Report',
        description: 'Patient-friendly summary of trial information',
        features: ['Plain language', 'Risk-benefit analysis', 'Eligibility criteria', 'Contact information'],
    },
];

const mockGeneratedContent = `# Clinical Trial Research Summary

## Executive Summary
This comprehensive analysis examines recent developments in Type 2 Diabetes Mellitus treatment protocols based on current CTRI registered trials.

## Key Findings
- **Phase III trials show 23% improvement** in HbA1c reduction compared to standard care
- **Novel GLP-1 agonists demonstrate** superior cardiovascular outcomes
- **Patient adherence rates increased by 34%** with new delivery mechanisms

## Statistical Analysis
### Primary Endpoints
- HbA1c reduction: -1.8% (95% CI: -2.1 to -1.5, p<0.001)
- Weight loss: -4.2 kg (95% CI: -5.1 to -3.3, p<0.001)
- Cardiovascular events: HR 0.76 (95% CI: 0.62-0.93, p=0.008)

### Secondary Endpoints
- Quality of life scores improved by 18.5 points
- Hypoglycemic episodes reduced by 42%
- Treatment satisfaction increased significantly (p<0.05)

## Clinical Implications
The evidence suggests that newer therapeutic approaches offer substantial benefits for T2DM management, particularly in:
1. Glycemic control optimization
2. Cardiovascular risk reduction
3. Patient quality of life enhancement

## References
1. Kumar, R. et al. (2024). "Novel GLP-1 Agonist Efficacy in Indian Population." *Indian Journal of Endocrinology*, 28(3), 145-152.
2. Sharma, P. et al. (2024). "Cardiovascular Outcomes in Diabetes Management." *Journal of Clinical Medicine*, 15(7), 234-241.
3. Patel, A. et al. (2024). "Patient-Centered Diabetes Care Approaches." *Diabetes Research and Clinical Practice*, 42(2), 89-96.

---
*Generated by AI Clinical Research Assistant | ${new Date().toLocaleDateString()} | Confidence: 94%*`;

export const SimpleDocumentDemo: React.FC = () => {
    const [selectedTemplate, setSelectedTemplate] = useState<string | null>(null);
    const [isGenerating, setIsGenerating] = useState(false);
    const [generatedContent, setGeneratedContent] = useState<string>('');
    const [showContent, setShowContent] = useState(false);

    const handleTemplateSelect = (templateId: string) => {
        setSelectedTemplate(templateId);
        setShowContent(false);
        setGeneratedContent('');
    };

    const handleGenerate = () => {
        if (!selectedTemplate) return;

        setIsGenerating(true);
        setShowContent(false);

        // Simulate AI generation with streaming effect
        setTimeout(() => {
            setIsGenerating(false);
            setGeneratedContent(mockGeneratedContent);
            setShowContent(true);
        }, 3000);
    };

    const handleDownload = () => {
        const blob = new Blob([generatedContent], { type: 'text/markdown' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = 'clinical-trial-summary.md';
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    };

    return (
        <DemoContainer>
            <Typography variant="h5" gutterBottom sx={{ fontWeight: 600, mb: 3 }}>
                🤖 AI Document Generation Demo
            </Typography>

            <Typography variant="body1" color="text.secondary" sx={{ mb: 4 }}>
                Generate professional research summaries and literature reviews with GPT-4 powered AI.
                Select a template and watch the AI create comprehensive documents in real-time.
            </Typography>

            {/* Template Selection */}
            <Typography variant="h6" gutterBottom sx={{ fontWeight: 600, mb: 2 }}>
                1. Choose Document Template
            </Typography>

            <Box sx={{
                display: 'grid',
                gridTemplateColumns: { xs: '1fr', md: 'repeat(3, 1fr)' },
                gap: 3,
                mb: 4
            }}>
                {templates.map((template) => (
                    <Box key={template.id}>
                        <TemplateCard
                            className={selectedTemplate === template.id ? 'selected' : ''}
                            onClick={() => handleTemplateSelect(template.id)}
                        >
                            <CardContent>
                                <Box sx={{ display: 'flex', alignItems: 'center', mb: 2 }}>
                                    <DocumentIcon sx={{ mr: 1, color: colors.primary.main }} />
                                    <Typography variant="h6" sx={{ fontWeight: 600 }}>
                                        {template.title}
                                    </Typography>
                                </Box>

                                <Typography variant="body2" color="text.secondary" sx={{ mb: 2 }}>
                                    {template.description}
                                </Typography>

                                <Box sx={{ display: 'flex', flexWrap: 'wrap', gap: 0.5 }}>
                                    {template.features.map((feature, index) => (
                                        <Chip
                                            key={index}
                                            label={feature}
                                            size="small"
                                            sx={{
                                                fontSize: '0.75rem',
                                                backgroundColor: alpha(colors.primary.main, 0.1),
                                                color: colors.primary.dark,
                                            }}
                                        />
                                    ))}
                                </Box>
                            </CardContent>
                        </TemplateCard>
                    </Box>
                ))}
            </Box>

            {/* Generation Controls */}
            {selectedTemplate && (
                <Fade in timeout={600}>
                    <Box sx={{ mb: 4 }}>
                        <Typography variant="h6" gutterBottom sx={{ fontWeight: 600, mb: 2 }}>
                            2. Generate Document
                        </Typography>

                        <Alert severity="info" sx={{ mb: 3 }}>
                            Selected template: <strong>{templates.find(t => t.id === selectedTemplate)?.title}</strong>
                            <br />
                            The AI will analyze sample clinical trials and generate a comprehensive document using GPT-4.
                        </Alert>

                        <Box sx={{ display: 'flex', gap: 2, alignItems: 'center' }}>
                            <Button
                                variant="contained"
                                size="large"
                                startIcon={isGenerating ? <AIIcon /> : <PlayIcon />}
                                onClick={handleGenerate}
                                disabled={isGenerating}
                                sx={{ minWidth: 200 }}
                            >
                                {isGenerating ? 'Generating...' : 'Generate Document'}
                            </Button>

                            {showContent && (
                                <Button
                                    variant="outlined"
                                    startIcon={<DownloadIcon />}
                                    onClick={handleDownload}
                                >
                                    Download
                                </Button>
                            )}
                        </Box>

                        {isGenerating && (
                            <Box sx={{ mt: 3 }}>
                                <Typography variant="body2" color="text.secondary" sx={{ mb: 1 }}>
                                    AI is analyzing clinical trials and generating your document...
                                </Typography>
                                <LinearProgress
                                    sx={{
                                        height: 8,
                                        borderRadius: 4,
                                        backgroundColor: alpha(colors.primary.main, 0.1),
                                        '& .MuiLinearProgress-bar': {
                                            borderRadius: 4,
                                            background: `linear-gradient(90deg, ${colors.primary.main}, ${colors.secondary.main})`,
                                        },
                                    }}
                                />
                                <Box sx={{ mt: 2, fontSize: '0.875rem', color: 'text.secondary' }}>
                                    <Typography variant="body2" sx={{ mb: 0.5 }}>
                                        ✓ Analyzing trial data and methodology
                                    </Typography>
                                    <Typography variant="body2" sx={{ mb: 0.5 }}>
                                        ✓ Extracting key findings and statistical results
                                    </Typography>
                                    <Typography variant="body2" sx={{ mb: 0.5 }}>
                                        ✓ Generating citations and references
                                    </Typography>
                                    <Typography variant="body2">
                                        ✓ Formatting document according to template
                                    </Typography>
                                </Box>
                            </Box>
                        )}
                    </Box>
                </Fade>
            )}

            {/* Generated Content */}
            {showContent && generatedContent && (
                <Fade in timeout={800}>
                    <Box>
                        <Typography variant="h6" gutterBottom sx={{ fontWeight: 600, mb: 2 }}>
                            3. Generated Document
                        </Typography>

                        <Alert severity="success" sx={{ mb: 3 }}>
                            Document generated successfully! The AI has created a comprehensive research summary
                            with proper citations and statistical analysis.
                        </Alert>

                        <GeneratedContent>
                            <pre style={{ margin: 0, whiteSpace: 'pre-wrap', fontFamily: 'inherit' }}>
                                {generatedContent}
                            </pre>
                        </GeneratedContent>

                        <Box sx={{ mt: 3, display: 'flex', gap: 2 }}>
                            <Button
                                variant="contained"
                                startIcon={<DownloadIcon />}
                                onClick={handleDownload}
                            >
                                Download Document
                            </Button>
                            <Button
                                variant="outlined"
                                onClick={() => {
                                    setShowContent(false);
                                    setGeneratedContent('');
                                    setSelectedTemplate(null);
                                }}
                            >
                                Generate Another
                            </Button>
                        </Box>
                    </Box>
                </Fade>
            )}
        </DemoContainer>
    );
};

export default SimpleDocumentDemo;