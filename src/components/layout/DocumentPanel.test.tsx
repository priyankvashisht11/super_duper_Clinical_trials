const renderWithTheme = (component: React.ReactElement) => {
  return render(
    <ThemeProvider theme={theme}>
      {component}
    </ThemeProvider>
  );
};

describe('DocumentPanel', () => {
  const mockOnToggle = vi.fn();
  const mockOnTrialRemove = vi.fn();

  beforeEach(() => {
    vi.clearAllMocks();
  });

  test('renders document panel when open', () => {
    renderWithTheme(
      <DocumentPanel
        open={true}
        onToggle={mockOnToggle}
        selectedTrials={mockSelectedTrials}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    expect(screen.getByText('Research Document')).toBeInTheDocument();
    expect(screen.getByText('Selected Trials (2)')).toBeInTheDocument();
  });

  test('displays selected trials correctly', () => {
    renderWithTheme(
      <DocumentPanel
        open={true}
        onToggle={mockOnToggle}
        selectedTrials={mockSelectedTrials}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    expect(screen.getByText('CTRI/2024/01/012345')).toBeInTheDocument();
    expect(screen.getByText('CTRI/2024/01/012346')).toBeInTheDocument();
    expect(screen.getByText(/Efficacy of Novel Diabetes Treatment/)).toBeInTheDocument();
    expect(screen.getByText(/Phase III Study of Hypertension Drug/)).toBeInTheDocument();
  });

  test('shows empty state when no trials selected', () => {
    renderWithTheme(
      <DocumentPanel
        open={true}
        onToggle={mockOnToggle}
        selectedTrials={[]}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    expect(screen.getByText('No trials selected. Select trials from the search results to generate documents.')).toBeInTheDocument();
  });

  test('handles trial removal', () => {
    renderWithTheme(
      <DocumentPanel
        open={true}
        onToggle={mockOnToggle}
        selectedTrials={mockSelectedTrials}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    const deleteButtons = screen.getAllByTestId('DeleteIcon');
    fireEvent.click(deleteButtons[0]);

    expect(mockOnTrialRemove).toHaveBeenCalledWith('1');
  });

  test('enables generate button when research question is entered', () => {
    renderWithTheme(
      <DocumentPanel
        open={true}
        onToggle={mockOnToggle}
        selectedTrials={mockSelectedTrials}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    const generateButton = screen.getByRole('button', { name: /Generate/i });
    expect(generateButton).toBeDisabled();

    const researchQuestionInput = screen.getByPlaceholderText(/What are the latest treatment approaches/i);
    fireEvent.change(researchQuestionInput, { target: { value: 'Test research question' } });

    expect(generateButton).toBeEnabled();
  });

  test('generates document when button is clicked', async () => {
    renderWithTheme(
      <DocumentPanel
        open={true}
        onToggle={mockOnToggle}
        selectedTrials={mockSelectedTrials}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    // Enter research question
    const researchQuestionInput = screen.getByPlaceholderText(/What are the latest treatment approaches/i);
    fireEvent.change(researchQuestionInput, { target: { value: 'Test research question' } });

    // Click generate button
    const generateButton = screen.getByRole('button', { name: /Generate/i });
    fireEvent.click(generateButton);

    // Check loading state
    expect(screen.getAllByText('Generating Document...')[0]).toBeInTheDocument();

    // Wait for document to be generated
    await waitFor(() => {
      expect(screen.getByText('Generated Document')).toBeInTheDocument();
    }, { timeout: 3000 });
  });

  test('allows template selection', () => {
    renderWithTheme(
      <DocumentPanel
        open={true}
        onToggle={mockOnToggle}
        selectedTrials={mockSelectedTrials}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    const templateSelect = screen.getByDisplayValue('literature_review');
    expect(templateSelect).toBeInTheDocument();
  });

  test('allows citation style selection', () => {
    renderWithTheme(
      <DocumentPanel
        open={true}
        onToggle={mockOnToggle}
        selectedTrials={mockSelectedTrials}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    const citationSelect = screen.getByDisplayValue('ama');
    expect(citationSelect).toBeInTheDocument();
  });

  test('does not render when closed', () => {
    renderWithTheme(
      <DocumentPanel
        open={false}
        onToggle={mockOnToggle}
        selectedTrials={mockSelectedTrials}
        onTrialRemove={mockOnTrialRemove}
      />
    );

    expect(screen.queryByText('Research Document')).not.toBeInTheDocument();
  });
});